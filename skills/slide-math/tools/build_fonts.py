"""Embed the bundled fonts in the theme as base64 WOFF2.

Writes theme/math-fonts.css, which theme/math.css imports. Marp inlines the theme
into each exported HTML, so a relative url() to a font file would not resolve;
embedding keeps the HTML, PDF and PNG exports identical on any machine, offline.

Run (only when a font file changes):
    uv run ~/.claude/skills/slide-math/tools/build_fonts.py
Do not open math-fonts.css: it is one long base64 line per face.
"""

import base64
import io
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

SKILL = Path(__file__).resolve().parent.parent
FONTS = SKILL / "fonts"
OUT = SKILL / "theme" / "math-fonts.css"

# Latin, Latin-1, Latin Extended-A/B, Greek, punctuation, super/subscripts,
# currency, letterlike, arrows, math operators, geometric shapes (for the
# triangle and disc glyphs), and the replacement character.
UNICODES = (
    "U+0000-024F,U+0370-03FF,U+1E00-1EFF,U+2000-206F,U+2070-209F,U+20A0-20CF,"
    "U+2100-214F,U+2190-21FF,U+2200-22FF,U+2300-23FF,U+25A0-25FF,U+2600-26FF,"
    "U+2700-27BF,U+FFFD"
)

FACES = [
    # (css family, file, weight, style)
    ("Source Sans 3", "SourceSans3-Regular.otf", 400, "normal"),
    ("Source Sans 3", "SourceSans3-It.otf", 400, "italic"),
    ("Source Sans 3", "SourceSans3-Semibold.otf", 600, "normal"),
    ("Source Sans 3", "SourceSans3-SemiboldIt.otf", 600, "italic"),
    ("Source Sans 3", "SourceSans3-Bold.otf", 700, "normal"),
    ("Source Sans 3", "SourceSans3-BoldIt.otf", 700, "italic"),
    ("Source Code Pro", "SourceCodePro-Regular.otf", 400, "normal"),
    ("Source Code Pro", "SourceCodePro-Semibold.otf", 600, "normal"),
    ("Source Serif 4 Display", "SourceSerif4Display-Bold.otf", 700, "normal"),
    ("Source Serif 4 Display", "SourceSerif4Display-Black.otf", 900, "normal"),
]


def woff2(path: Path) -> bytes:
    font = TTFont(path)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=subset.parse_unicodes(UNICODES))
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    return buf.getvalue()


def main() -> None:
    parts = [
        "/* @theme math-fonts */\n",
        "/* Generated by tools/build_fonts.py from fonts/*.otf (SIL OFL 1.1). Do not edit or read. */\n",
    ]
    total = 0
    for family, fname, weight, style in FACES:
        data = woff2(FONTS / fname)
        total += len(data)
        b64 = base64.b64encode(data).decode("ascii")
        parts.append(
            f"@font-face{{font-family:'{family}';font-weight:{weight};font-style:{style};"
            f"font-display:block;src:url(data:font/woff2;base64,{b64}) format('woff2');}}\n"
        )
    OUT.write_text("".join(parts))
    print(f"wrote {OUT} ({total/1024:.0f} KiB of WOFF2, {OUT.stat().st_size/1024:.0f} KiB CSS)")


if __name__ == "__main__":
    main()
